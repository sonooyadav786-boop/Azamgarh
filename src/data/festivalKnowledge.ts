/**
 * Universal resolver for festival knowledge:
 * Returns authentic Puja Vidhi, Why it is celebrated, and Since when it is celebrated.
 */
export function getFestivalDetails(event?: CalendarEvent | null): {
  title: string;
  pujaVidhi: string;
  whyCelebrated: string;
  historySince: string;
  muhurat: string;
} {
  if (!event) {
    return {
      title: 'दैनिक वैदिक पंचांग एवं आराधना',
      pujaVidhi: 'प्रातःकाल सूर्योदय से पूर्व उठकर दैनिक नित्यकर्म व स्नान करें। उगते सूर्य को तांबे के पात्र से जल में रोली व अक्षत मिलाकर अर्घ्य दें। कुलदेवता, इष्टदेव तथा भगवान शिव व श्री विष्णु का पंचोपचार विधि (गंध, पुष्प, धूप, दीप, नैवेद्य) से पूजन करें।',
      whyCelebrated: 'सनातन वैदिक धर्म में प्रत्येक तिथि और दिवस किसी न किसी दिव्य शक्ति का वास माना गया है। दैनिक पंचांग के अनुसार आचरण करने से कर्मों में शुद्धि, कालदोष का निवारण और जीवन में सात्विक ऊर्जा की वृद्धि होती है।',
      historySince: 'सृष्टि के आरंभ से वेदों और स्मृतियों में सूर्य, चन्द्रमा एवं पंच-महाभूतों की दैनिक पूजा का विधान निरूपित है।',
      muhurat: 'अभिजित मुहूर्त व प्रातः काल सर्वश्रेष्ठ फलदायी है।',
    };
  }

  // 1. If explicitly defined on the event itself
  if (event.whyCelebratedHindi && event.historySinceHindi && event.vidhiHindi) {
    return {
      title: event.titleHindi,
      pujaVidhi: event.vidhiHindi,
      whyCelebrated: event.whyCelebratedHindi,
      historySince: event.historySinceHindi,
      muhurat: event.muhuratTime || 'दिन के चौघड़िया व अभिजित मुहूर्त में पूजन करें।',
    };
  }

  // 2. Search pattern in database
  const searchKey = `${event.id} ${event.titleHindi} ${event.category} ${event.imageType}`.toLowerCase();
  for (const item of FESTIVAL_KNOWLEDGE_BASE) {
    const matched = item.idPatterns.some((pattern) => searchKey.includes(pattern.toLowerCase()));
    if (matched) {
      return {
        title: event.titleHindi,
        pujaVidhi: event.vidhiHindi || item.pujaVidhi,
        whyCelebrated: event.whyCelebratedHindi || (event.descriptionHindi ? `${event.descriptionHindi} ${item.whyCelebrated}` : item.whyCelebrated),
        historySince: event.historySinceHindi || item.historySince,
        muhurat: event.muhuratTime || 'पंचांग में वर्णित शुभ चौघड़िया व अभिजित मुहूर्त में पूजन करें।',
      };
    }
  }

  // 3. Fallback based on category
  let defaultVidhi = 'प्रातः स्नान के उपरांत पूजा स्थल को गंगाजल से पवित्र करें। इष्टदेव का ध्यान कर धूप, दीप, अक्षत, पुष्प और फल अर्पित करें। संबंधित स्तोत्र या चालीसा का पाठ करें और आरती उतारें।';
  let defaultWhy = event.descriptionHindi || 'इस पावन पर्व पर उपवास, ईश्वर आराधना, दान-पुण्य और सत्कर्म करने से पापों का शमन और आत्मिक शांति प्राप्त होती है।';
  let defaultHistory = 'वैदिक काल तथा पौराणिक संहिताओं से यह पर्व एवं व्रत परंपरा सनातन धर्म में अनवरत चली आ रही है।';

  if (event.category === 'vrat') {
    defaultVidhi = 'सूर्योदय से पूर्व स्नान कर व्रत का संकल्प लें। पूरे दिन निराहार या फलाहार रहें। सायंकाल देव पूजन व कथा श्रवण के उपरांत ही प्रसाद ग्रहण करें।';
    defaultWhy = `${event.titleHindi} का व्रत करने से मन की शुद्धि, पारिवारिक शांति और मनोवांछित फल की प्राप्ति होती है।`;
    defaultHistory = 'स्मृति व पुराण ग्रंथों में वर्णित काल से इस व्रत का अनुष्ठान किया जाता है।';
  } else if (event.category === 'amavasya' || event.category === 'shradh') {
    defaultVidhi = 'दोपहर कुतुप मुहूर्त में तिल, कुश और जल से तर्पण करें। पूर्वजों के निमित्त ग्रास निकालें और गरीबों या ब्राह्मणों को भोजन-वस्त्र दान करें।';
    defaultWhy = 'पूर्वजों की आत्मा की शांति, पितृदोष से मुक्ति और पितरों के आशीर्वाद से वंश वृद्धि हेतु यह दिन परम कल्याणकारी है।';
    defaultHistory = 'ऋग्वैदिक काल से सनातन समाज में पितृ यज्ञ और तर्पण की परंपरा अविरल प्रवाहित है।';
  } else if (event.category === 'purnima') {
    defaultVidhi = 'पवित्र नदी स्नान अथवा घर में गंगाजल मिलाकर स्नान करें। भगवान सत्यनारायण का पूजन, कथा श्रवण एवं चंद्रोदय पर चंद्रमा को अर्घ्य दें।';
    defaultWhy = 'पूर्णिमा तिथि पर चन्द्रमा की षोडश कलाओं का प्रभाव पृथ्वी पर पूर्ण रहता है। इस दिन दान-पुण्य का सहस्त्र गुना फल मिलता है।';
    defaultHistory = 'वैदिक काल से पूर्णिमा पर यज्ञ, हवन और सत्यनारायण कथा का विधान प्रचलित है।';
  }

  return {
    title: event.titleHindi,
    pujaVidhi: event.vidhiHindi || defaultVidhi,
    whyCelebrated: event.whyCelebratedHindi || defaultWhy,
    historySince: event.historySinceHindi || defaultHistory,
    muhurat: event.muhuratTime || 'शुभ मुहूर्त व अभिजित काल में पूजन करें।',
  };
}

/**
 * Determine if an event is a "Bada Tyohar" (Major Festival)
 * Major festivals get prominent crimson/red gradient badges with white bold text,
 * while minor festivals/vrats get soft amber/gold badges.
 */
export function isMajorFestival(event?: CalendarEvent | null): boolean {
  if (!event) return false;
  if (event.isMajor !== undefined) return event.isMajor;
  if (event.isGazettedHoliday) return true;
  return /दीपावली|दिवाली|दशहरा|विजयादशमी|छठ पूजा|नवरात्रि|करवा चौथ|धनतेरस|गोवर्धन|होली|महाशिवरात्रि|जन्माष्टमी|राम नवमी|रक्षाबंधन|संक्रान्ति|देव दीपावली|तुलसी विवाह|सर्वपितृ/.test(
    event.titleHindi
  );
}

